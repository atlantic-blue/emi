/**
 * The two artifacts Terraform reads, written from the TypeScript beside them.
 *
 * Neither runtime reads TypeScript. CloudFront evaluates a script and calls a global named
 * `handler`, so the script carries no `export`. A Lambda runtime resolves `index.handler` by file
 * extension and never finds a `.ts` file at all, so the placeholder ships as `index.mjs`.
 *
 * The types are taken out by the same call Node itself uses to run TypeScript, so the artifact is
 * the source with its types blanked and nothing else. The result is formatted the way the
 * repository formats every other file, so the committed artifact passes the format check.
 *
 * Two directories are passed in rather than read from this file. The first says where the
 * formatting rules of the repository are found, and the second says where the sources are read
 * from, so a test can read a copy and still be formatted the way the committed artifact is.
 */

import { readFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
import { join } from 'node:path';

import { format, resolveConfig } from 'prettier';

export interface Artifact {
  /** The path under the module directory, which is the path Terraform reads. */
  readonly file: string;
  readonly contents: string;
}

const banner = (source: string): string =>
  [
    `// Written from src/${source} by src/write.ts. Do not edit this file.`,
    '// node --disable-warning=ExperimentalWarning --experimental-strip-types \\',
    '//   infrastructure/modules/nextjs-site/src/write.ts',
    '',
  ].join('\n');

async function artifactOf(
  formatAs: string,
  readFrom: string,
  source: string,
  file: string,
  asScript: boolean,
): Promise<Artifact> {
  const typescript = readFileSync(join(readFrom, 'src', source), 'utf8');
  const javascript = stripTypeScriptTypes(typescript, { mode: 'strip' });
  const script = asScript ? javascript.replace(/^export /gm, '') : javascript;
  const path = join(formatAs, file);
  const options = await resolveConfig(path);
  const contents = await format(banner(source) + script, {
    ...options,
    filepath: path,
    parser: 'babel',
  });

  return { file, contents };
}

/** Both artifacts, in the order a reader meets them: the edge first, then the origin. */
export async function artifactsOf(formatAs: string, readFrom = formatAs): Promise<Artifact[]> {
  return [
    await artifactOf(formatAs, readFrom, 'redirect.ts', join('code', 'redirect.js'), true),
    await artifactOf(formatAs, readFrom, 'placeholder.ts', join('code', 'index.mjs'), false),
  ];
}
